#include <JoSIM/Constants.hpp>
#include <JoSIM/Input.hpp>
#include <JoSIM/Matrix.hpp>
#include <JoSIM/Simulation.hpp>

#include <algorithm>
#include <cmath>
#include <iomanip>
#include <iostream>
#include <limits>
#include <stdexcept>

using namespace JoSIM;

static void require(bool condition, const char* message) {
    if (!condition) { throw std::runtime_error(message); }
}

static void constant_voltage(AnalysisType mode, double voltage, double h, int64_t count) {
    Input input(mode, 0, true);
    input.transSim.tstep(h);
    input.transSim.tstop((count + 0.25) * h); // Keep the requested integer count away from a floating boundary.
    input.transSim.startup(false);
    Model model;
    model.modelName("JM");
    model.rtype(0);
    model.ic(1e-4);
    model.rn(10);
    model.c(1e-13);
    input.netlist.models_new.emplace_back(model, std::nullopt);
    input.netlist.expNetlist = {{{"V1", "N", "0", "DC", voltage > 0 ? "1m" : "-1m"}, std::nullopt},
                               {{"B1", "N", "0", "JM"}, std::nullopt}};
    Matrix matrix;
    matrix.create_matrix(input);
    Simulation simulation(input, matrix);
    require(input.transSim.tstep() == h, "A constant-bias reference unexpectedly retried its timestep");
    const auto& jj = std::get<JJ>(matrix.components.devices.at(matrix.components.junctionIndices.at(0)));
    const auto& source = std::get<VoltageSource>(matrix.components.devices.at(matrix.components.vsIndices.at(0)));
    const auto& phase = *simulation.results.xVector.at(mode == AnalysisType::Voltage ? jj.variableIndex_ : matrix.nm.at("N"));
    const auto& volts = *simulation.results.xVector.at(mode == AnalysisType::Voltage ? matrix.nm.at("N") : jj.variableIndex_);
    const auto& current = *simulation.results.xVector.at(*jj.indexInfo.currentIndex_);
    const auto& supplied = *simulation.results.xVector.at(*source.indexInfo.currentIndex_);
    require(phase.size() == static_cast<size_t>(count), "Constant-bias reference has an unexpected grid");
    // After the cold-start transient, Josephson's relation independently gives
    // phi(t)-phi(t_anchor)=V*(t-t_anchor)/sigma. Anchor the arbitrary phase origin;
    // no discrete recurrence or expected data generated by the solver is used.
    const size_t anchor = 100;
    double drift = 0, constitutive = 0, kcl = 0, verror = 0;
    for (size_t i = anchor; i < phase.size(); ++i) {
        require(std::isfinite(phase[i]) && std::isfinite(volts[i])
                && std::isfinite(current[i]) && std::isfinite(supplied[i]), "Non-finite junction reference sample");
        const double expected = voltage * ((i - anchor) * h) / Constants::SIGMA;
        drift = std::max(drift, std::abs((phase[i] - phase[anchor]) - expected));
        const double expectedCurrent = model.ic() * std::sin(phase[i]) + voltage / model.rn();
        constitutive = std::max(constitutive, std::abs(current[i] - expectedCurrent));
        kcl = std::max(kcl, std::abs(current[i] + supplied[i]));
        verror = std::max(verror, std::abs(volts[i] - voltage));
    }
    // Conservative accumulated double-rounding allowance: O(eps*q*N^2),
    // q=|V*h/sigma|. This differs from changing the physical model coefficient.
    const double tolerance = 8 * std::numeric_limits<double>::epsilon()
        * std::abs(voltage * h / Constants::SIGMA) * double(count) * double(count) + 1e-10;
    std::cout << int(mode) << ',' << voltage << ',' << h << ',' << count << ',' << drift << ','
              << tolerance << ',' << constitutive << ',' << kcl << ',' << verror << '\n';
    require(std::isfinite(drift) && drift <= tolerance, "JJ accumulated phase violates the constant-voltage Josephson relation");
    require(std::isfinite(constitutive) && constitutive < 1e-10, "Steady JJ current violates Ic*sin(phi)+V/R");
    require(kcl < 1e-15, "Constant-bias junction violates KCL");
    require(verror < 1e-10, "Constant-bias junction voltage changed");
}

int main() {
    try {
        std::cout << std::setprecision(17)
                  << "mode,voltage_V,h_s,steps,phase_drift_rad,tolerance_rad,current_residual_A,KCL_A,voltage_error_V\n";
        for (auto mode : {AnalysisType::Voltage, AnalysisType::Phase}) {
            for (double voltage : {1e-3, -1e-3}) {
                for (double h : {1e-14, 1e-13}) {
                    for (int64_t count : {10000, 100000, 1000000}) { constant_voltage(mode, voltage, h, count); }
                }
            }
        }
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
